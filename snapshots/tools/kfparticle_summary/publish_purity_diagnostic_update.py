#!/usr/bin/env python3
"""Replace one verified report PDF while preserving its exact preceding version."""
import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import shutil

from build_method6_report import pdf_pages


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--backup-dir', type=Path, required=True)
    args = parser.parse_args()
    out = args.output_dir.resolve(strict=True)
    metadata = json.loads((out/'diagnostic_report_metadata.json').read_text())
    validation = json.loads((out/'validation.json').read_text())
    if metadata['phase'] != 'staged' or validation['phase'] != 'validated':
        raise ValueError('A staged report and successful validation are required.')
    source = Path(metadata['report']['path']).resolve(strict=True)
    target = Path(metadata['originalReport']['path']).resolve(strict=True)
    if sha(source) != metadata['report']['sha256'] or sha(target) != metadata['originalReport']['sha256']:
        raise ValueError('Staged or original report has changed.')
    if validation['reportSha256'] != sha(source):
        raise ValueError('Validation does not describe the staged report.')
    if source == target or pdf_pages(source) != metadata['report']['pages']:
        raise ValueError('Invalid replacement path or page count.')
    backup = args.backup_dir.resolve()
    if backup.exists():
        raise ValueError('Refusing an existing backup directory.')
    backup.mkdir(parents=True)
    preserved = backup/target.name
    shutil.copy2(str(target),str(preserved))
    if sha(preserved) != metadata['originalReport']['sha256']:
        raise ValueError('Backup verification failed.')
    temporary = target.with_name(target.name+'.diagnostic-update.tmp')
    if temporary.exists():
        raise ValueError('Refusing an existing publication temporary file.')
    shutil.copy2(str(source),str(temporary))
    if sha(temporary) != metadata['report']['sha256']:
        raise ValueError('Temporary replacement verification failed.')
    os.replace(str(temporary),str(target))
    if sha(target) != sha(source):
        raise ValueError('Published report hash mismatch.')
    result=dict(phase='published',publishedAtJst=datetime.datetime.now(
        datetime.timezone(datetime.timedelta(hours=9))).isoformat(),
        target=str(target),sha256=sha(target),pages=metadata['report']['pages'],
        bytes=target.stat().st_size,backup=str(preserved),backupSha256=sha(preserved),
        stagedSource=str(source),validationSha256=sha(out/'validation.json'))
    (out/'publication.json').write_text(json.dumps(result,indent=2)+'\n')
    (backup/'preservation.json').write_text(json.dumps(result,indent=2)+'\n')
    # The original TeX and fit reports remain reference records, not sources of this update.
    note=target.with_name('summary_update_'+datetime.datetime.now(
        datetime.timezone(datetime.timedelta(hours=9))).strftime('%Y%m%d')+'.md')
    note.write_text('# CF report update\n\nThe current summary PDF contains a new reading guide, '
        'the preserved original report, and a diagnostic addendum. The original figure numbers '
        'remain in the reference section. Updated normalization comparisons in the addendum '
        'take precedence over reference CFs where explicitly stated; reference LL fits are not refitted.\n\n'
        '- Assembly and numerical records: ['+str(out)+']('+str(out)+')\n'
        '- Preserved preceding PDF: ['+str(preserved)+']('+str(preserved)+')\n'
        '- Publication record: ['+str(out/'publication.json')+']('+str(out/'publication.json')+')\n\n'
        'The original TeX and report metadata describe the preceding reference report. '
        'The current PDF is generated by build_purity_diagnostic_update.py; its inputs, '
        'source hashes and figure pages are recorded in diagnostic_report_metadata.json.\n')
    print(json.dumps(result))


if __name__ == '__main__':
    main()
